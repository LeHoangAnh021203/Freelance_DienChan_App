/// Transcribed from user-supplied tables pp.152–153 and checked against
/// frontal/profile diagrams pp.154–155. Ranges identify cells, not exact dots.
class BqcGridReference {
  const BqcGridReference(
    this.column,
    this.row, {
    this.side = 'both',
    this.page = 152,
    this.note = '',
  });
  final String column, row, note;
  // Side is relative to the displayed frontal drawing, not patient's laterality.
  final String side;
  final int page;
  bool get frontSupported =>
      column.split('-').every(_columns.containsKey) &&
      row.split('-').every((r) => _rows.containsKey(int.tryParse(r)));
  String get description =>
      'Bảng tr. $page: $column / $row${side == 'none' ? ' · tham chiếu trắc diện/vùng riêng' : ''}${note.isEmpty ? '' : ' · $note'}';

  List<Rect> get regions {
    if (!frontSupported || side == 'none') return const [];
    final cs = column.split('-').map((c) => _columns[c]!).toList()..sort();
    final rs = row.split('-').map((r) => _rows[int.parse(r)]!).toList();
    Rect region(bool left) {
      final x1 = 432 + (left ? -cs.last : cs.first);
      final x2 = 432 + (left ? -cs.first : cs.last);
      return Rect.fromLTRB(x1 / 864, rs.first / 1152, x2 / 864, rs.last / 1152);
    }

    if (column == 'O') return [region(false)];
    return [
      if (side != 'right') region(true),
      if (side != 'left') region(false),
    ];
  }
}

