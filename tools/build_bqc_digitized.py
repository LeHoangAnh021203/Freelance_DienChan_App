"""Generate source-traceable face coordinates; no raster image modification.
Input coordinates are manually read in the 1368x1824 preview coordinate frame.
Piecewise grid registration compensates local row slope and column convergence.
It does not reconstruct page curvature or establish clinical accuracy.
"""
import csv, json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
rows = list(csv.DictReader((root/'docs/references/bqc-front-dots.csv').open()))
assert len({r['code'] for r in rows}) == len(rows)
source_rows = [380,457,534,616,694,770,845,936,1014,1115,1210,1313,1414]
edge_rows = [353,431,513,599,682,755,834,933,1008,1115,1213,1318,1420]
target_rows = [250,300,350,402,445,500,550,635,695,745,810,885,941]
source_columns_top = [576,597,618,644,665,709,750,792,833,888,924]
source_columns_bottom = [590,607,637,664,690,736,782,827,877,931,970]
target_columns = [0,14,30,48,64,100,133,170,205,225,270]
def interp(v, xs, ys):
    i = next((i for i in range(len(xs)-1) if v <= xs[i+1]), len(xs)-2)
    return ys[i] + (v-xs[i])/(xs[i+1]-xs[i])*(ys[i+1]-ys[i])
def register(x,y):
    center = interp(y, [380,1414], [576,590])
    # Left-side observations use their own photographed column span.
    left = x < center
    if left:
        lx = [576,559,541,518,497,459,429,397,365,334,294]
        lb = [590,573,549,522,499,458,422,386,349,303,265]
        columns = [interp(y,[380,1414],[a,b]) for a,b in zip(lx,lb)]
        d = center-x
        src = [center-v for v in columns]
        slope = min(d/max(src[-2],1),1)
        local_rows = [a+(b-a)*slope for a,b in zip(source_rows,[441,502,578,640,726,797,866,952,1019,1114,1203,1294,1406])]
    else:
        columns = [interp(y,[380,1414],[a,b]) for a,b in zip(source_columns_top,source_columns_bottom)]
        d = x-center
        src = [v-center for v in columns]
        slope = min(d/max(src[-2],1),1)
        local_rows = [a+(b-a)*slope for a,b in zip(source_rows,edge_rows)]
    dx = interp(d,src,target_columns)
    return (432-dx if left else 432+dx)/864, interp(y,local_rows,target_rows)/1152
out = ["// Generated by tools/build_bqc_digitized.py; edit source CSV, not this file.", "import 'package:flutter/material.dart';", "", "const bqcDigitizedFront = <String, List<Offset>>{"]
for r in rows:
    x,y=register(float(r['x']),float(r['y']))
    if r['placement']=='midline': x=.5
    points=[(x,y)]
    if r['placement']=='bilateral': points.append((1-x,y))
    assert all(0<=a<=1 and 0<=b<=1 for a,b in points),r
    out.append("  '%s': [%s],"%(r['code'], ', '.join('Offset(%.8f, %.8f)'%(a,b) for a,b in points)))
out.append('};\n')
(root/'mobile/lib/bqc_digitized.dart').write_text('\n'.join(out))
# Review original photo with independent source dots; no generated bitmap.
html='''<!doctype html><meta charset="utf-8"><title>Đối chiếu chấm BQC trang 154</title>
<style>body{font:16px sans-serif}svg{width:100%;max-width:1368px}circle{fill:none;stroke:red;stroke-width:2}text{fill:blue;font-size:12px;paint-order:stroke;stroke:white;stroke-width:2px}</style>
<p>Chấm đỏ: vị trí đọc thủ công. Di chuột để xem mã. Tọa độ dùng khung ảnh 1368 × 1824; ảnh gốc được giữ nguyên. Hai bên được đối xứng khi chuyển sang mô hình.</p>
<svg viewBox="0 0 1368 1824" xmlns="http://www.w3.org/2000/svg"><image href="source-images/bqc-front-154.jpg" width="1368" height="1824"/>'''
for r in rows:
    html+=f'<g><title>Huyệt {r["code"]} ({r["placement"]})</title><circle cx="{r["x"]}" cy="{r["y"]}" r="5"/></g>'
html+='</svg>'
(root/'docs/references/bqc-front-review.html').write_text(html)
print(f'Generated {len(rows)} codes from observed frontal dots')
with (root/'mobile/lib/bqc_digitized.dart').open('a') as f:
    for name, filename in [('bqcFrontSourceDots','bqc-front-dots.csv'),('bqcSideSourceDots','bqc-side-dots.csv')]:
        data=list(csv.DictReader((root/'docs/references'/filename).open()))
        f.write('\nconst '+name+' = <String, Offset>{\n')
        for r in data:
            f.write("  '%s': Offset(%s / 1368, %s / 1824),\n"%(r['code'],r['x'],r['y']))
        f.write('};\n')
